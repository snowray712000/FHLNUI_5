/**
 * ### 信望愛希臘文內碼 (ASCII) → Unicode，對應 PHP gcode($itxt, 2)
 * 例 `to; pneu'ma mh; sbevnnute,` → `τὸ πνεῦμα μὴ σβέννυτε,`
 * - 重音輸出的是 oxia 版 (έ U+1F73)，與 FHL 資料庫、ssn.php 的 Unicode 查詢一致；鍵盤打的是 tonos (U+03AD)
 * - 來源 VirtualApi/api_php/gcode2.js；已用 bible_fhlwh.sqlite 全新約 7958 節與 qsb.php (fhlwh) 比對，除換行位置外全同
 * - 測試 tests/gcode2.test.js (npm test)
 */
function replaceAllLiteral(text, search, replacement) {
    return text.split(search).join(replacement);
}
function replaceByTable(text, fromList, toList) {
    let out = text;
    for (let i = 0; i < fromList.length; i += 1) {
        out = replaceAllLiteral(out, fromList[i], toList[i]);
    }
    return out;
}

