/**
 * 對應 PHP: gcode($itxt, 2)
 * @param {string} input
 * @returns {string}
 */
export function gcode_2(input) {
    let itxt = input == null ? '' : String(input);
    if (itxt.length === 0) return itxt;

    // bible_fhlwh.sqlite 的 txt 有 2 個字元是當初編碼轉換時弄錯的 (原本是單一 byte 的縮寫)
    // 由與 qsb.php 全新約比對推得：U+0358 (o͘) 是 u，U+1E73 (ṳ) 是 ii (只出現在 2 Tim 2:16)
    itxt = itxt.replace(/\u0358/g, 'u').replace(/\u1e73/g, 'ii');

    // PHP:
    // $txt=preg_replace("/s([-\r\n,.:;}{) ])/","{$ns}\\1",$itxt);
    // $txt=preg_replace('/s$/',$ns,$txt);
    const txt = itxt
        .replace(/s([-\r\n,.:;}{) ])/g, '"$1')
        .replace(/s$/g, '"');

    let ntxt = replaceByTable(txt, orga, uorg);
    ntxt = replaceByTable(ntxt, orgb, uorg);
    // PHP 沒有把落單的 v ; j J 另外轉換 (照原樣輸出)，已與 qsb.php 全新約比對
    ntxt = replaceByTable(ntxt, AD, UAD);
    return ntxt;
}
